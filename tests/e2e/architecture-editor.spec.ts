import { test, expect } from './fixtures';
import { readFile } from 'node:fs/promises';

test('architecture can be created, edited, saved and undone', async ({ page }) => {
  await page.goto('/');
  await page.getByText('문·창문·구역', { exact: true }).click();
  await page.getByRole('button', { name: '새 칸막이' }).click();
  await page.getByLabel('칸막이 이름').fill('욕실 벽');
  await page.getByRole('button', { name: '칸막이 저장' }).click();
  await expect(page.getByRole('button', { name: '욕실 벽 편집' })).toBeVisible();
  await page.getByRole('button', { name: '새 문' }).click();
  await page.getByLabel('개구부 이름').fill('출입문');
  await page.getByRole('button', { name: '개구부 저장' }).click();
  await expect(page.getByRole('button', { name: '출입문 편집' })).toBeVisible();
  await page.getByRole('button', { name: '새 창문' }).click();
  await page.getByLabel('개구부 이름').fill('창문 A');
  await page.getByLabel('개구부 시작 위치 (mm)').fill('1000');
  await page.getByRole('button', { name: '개구부 저장' }).click();
  await expect(page.getByRole('button', { name: '창문 A 편집' })).toBeVisible();
  await page.getByRole('button', { name: '새 구역' }).click();
  await page.getByLabel('구역 이름').fill('욕실');
  await page.getByLabel('구역 종류').selectOption('bathroom');
  await page.getByRole('button', { name: '구역 저장' }).click();
  await expect(page.getByRole('button', { name: '욕실 편집' })).toBeVisible();
  await page.getByRole('button', { name: '욕실 편집' }).click();
  await page.getByLabel('구역 가로 (mm)').fill('잘못된 값');
  await page.getByRole('button', { name: '구역 저장' }).click();
  await expect(page.getByRole('alert')).toContainText('정수');
  await page.getByLabel('구역 가로 (mm)').fill('900');
  await page.getByRole('button', { name: '구역 저장' }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'JSON 내보내기' }).click();
  const download = await downloadPromise;
  const exported = JSON.parse(await readFile(await download.path(), 'utf8'));
  expect(exported.room.partitions[0].name).toBe('욕실 벽');
  expect(exported.room.openings.map((item: {name:string}) => item.name)).toEqual(['출입문', '창문 A']);
  expect(exported.room.zones[0].widthMm).toBe(900);
  await page.getByRole('button', { name: '3D 보기', exact: true }).click();
  await expect(page.getByLabel('3D 방 보기').locator('canvas')).toBeVisible();
  await page.getByRole('button', { name: '2D에서 편집', exact: true }).click();
  const afterViewDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'JSON 내보내기', exact: true }).click();
  expect(JSON.parse(await readFile(await (await afterViewDownload).path(), 'utf8'))).toEqual(exported);
  // The shared property panel stays mounted and open across view changes.
  await expect(page.getByRole('button', { name: '욕실 편집' })).toBeVisible();
  await expect.poll(() => page.evaluate(() => localStorage.getItem('roomfit3d:v2:/:autosave'))).toContain('욕실 벽');
  await page.getByRole('button', { name: '실행 취소' }).click();
  await page.getByRole('button', { name: '욕실 편집' }).click();
  await expect(page.getByLabel('구역 가로 (mm)')).toHaveValue('1000');
});

test('hosted openings protect their partition and allow editing its host', async ({ page }) => {
  await page.goto('/');
  await page.getByText('문·창문·구역', { exact: true }).click();
  await page.getByRole('button', { name: '새 칸막이' }).click();
  await page.getByLabel('칸막이 이름').fill('안쪽 벽');
  await page.getByRole('button', { name: '칸막이 저장' }).click();
  await page.getByRole('button', { name: '새 문' }).click();
  await page.getByLabel('개구부 이름').fill('안쪽 문');
  await page.getByLabel('개구부 벽').selectOption({ label: '칸막이: 안쪽 벽' });
  await page.getByRole('button', { name: '개구부 저장' }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '안쪽 벽 삭제' }).click();
  await expect(page.getByRole('alert')).toContainText('먼저 삭제');
  await expect(page.getByRole('button', { name: '안쪽 벽 편집' })).toBeVisible();
});
